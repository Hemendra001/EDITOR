import assert from 'node:assert/strict';
import {compareSources,analyzeResume,jobTerms,smoothText} from '../src/review-engine.js';
import {rewriteParts} from '../src/writer.js';
const original='Regular practice helps people build confidence and improve their skills.';
let comparison=compareSources(original,[{name:'one',text:original},{name:'two',text:original}]);
assert.equal(comparison.percent,100);assert.equal(comparison.matchedWords,comparison.totalWords);
assert.equal(compareSources(original,[{name:'unrelated',text:'The red boat sailed across the blue sea yesterday.'}]).percent,0);
assert.throws(()=>compareSources(original,[]),/source/);
assert.equal(compareSources('One two three four five six seven eight',[{name:'a',text:'One two three four five'},{name:'b',text:'four five six seven eight'}]).percent,100);
const text=`Alex Morgan\nalex@example.com +1 415 555 1234\nExperience\n• Built React applications for 200 users.\n• Built TypeScript components\n• Built REST APIs.\nEducation\nBSc Computer Science\nSkills\nReact TypeScript JavaScript C++ Git`;
const jd='We need React TypeScript JavaScript C++ Git and Python. Testing and communication skills required.';
const report=analyzeResume(text,jd);
assert(report.matched.includes('c++'));assert(report.missing.includes('python'));assert(report.sections.find(s=>s.name==='Experience').index>=0);assert.equal(report.contact.email,'alex@example.com');assert(report.issues.some(i=>i.category==='Repetition'));assert(report.issues.some(i=>i.category==='Consistency'));assert.equal(report.quantified,1);
assert(analyzeResume(text+'\nPython Testing Communication',jd).scores.match>report.scores.match);
assert(analyzeResume(text,jd,{emptyPages:[1]}).scores.readability<report.scores.readability);
assert(!analyzeResume('2020 - 2024\nEducation','').contact.phone);
assert(!analyzeResume('JavaScript','Java').matched.includes('java'));
assert(smoothText('We utilize feedback in order to improve.').text.includes('use feedback to improve'));
assert.equal(smoothText('Revenue grew by 30% in 2024.').text,'Revenue grew by 30% in 2024.');
assert(rewriteParts('word '.repeat(500)).every(s=>s.length<=800));
console.log('Review checks passed: similarity coverage, no double-counting, boundaries, scores, contacts, rewriting.');
const {reviewRewrite}=await import('../src/rewrite-quality.js');
assert(reviewRewrite('Grew 30% in 2024.','Grew 30% in 2024 versus 2023.').reason);
assert(reviewRewrite('We did not change it.','We changed it.').reason);
assert.equal(reviewRewrite('We did not change it.','We did not modify it.').reason,null);
assert.equal(rewriteParts('Use Node.js and React.js for apps. Keep e.g. examples intact.').join(' '),'Use Node.js and React.js for apps. Keep e.g. examples intact.');
console.log('Rewrite fact-preservation checks passed.');

assert(reviewRewrite('Reduced load time by 30%.','Reduced load time to 30%.').reason);
const {roleContext,writingReview}=await import('../src/review-engine.js');
assert(roleContext('Developer').text.includes('Git'));
assert(roleContext('Data analyst').text.includes('SQL'));
assert(analyzeResume(text,'Developer').targetNote.includes('General skill'));
assert(writingReview('This is a clear sentence with a useful message.').score>writingReview('In order to improve the the text, we should utilize feedback on a daily basis.').score);
assert.throws(()=>writingReview(''),/at least/);
console.log('Short job titles and source-free writing scores passed.');

const {validateDetectorText,summarizeDetector}=await import('../src/detector.js');
assert.throws(()=>validateDetectorText('Too short'),/50 words/);
assert.throws(()=>validateDetectorText('word '.repeat(5001)),/5,000/);
assert.throws(()=>validateDetectorText('हिन्दी भाषा '.repeat(60)),/English/);
validateDetectorText('English text '.repeat(30));
assert.equal(summarizeDetector([{score:.9,tokens:100}]).label,'Leans AI-generated');
assert.equal(summarizeDetector([{score:.1,tokens:100}]).label,'Leans human-written');
assert.equal(summarizeDetector([{score:.6,tokens:100}]).label,'Inconclusive');
assert.equal(summarizeDetector([{score:.9,tokens:100},{score:.1,tokens:10}]).label,'Inconclusive · mixed signals');
assert.equal(summarizeDetector([{score:.7,tokens:30},{score:.3,tokens:10}]).score,.6);
assert.throws(()=>summarizeDetector([{score:NaN,tokens:10}]),/Invalid/);
console.log('Detector minimum length, limits, uncertainty and weighted aggregation passed.');
