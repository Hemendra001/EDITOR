import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {DOMMatrix,Path2D,ImageData} from '@napi-rs/canvas';
Object.assign(globalThis,{DOMMatrix,Path2D,ImageData});
Math.sumPrecise ??= values=>Array.from(values).reduce((a,b)=>a+b,0);
// Node 24 lacks a typed-array method available in the supported browser.
Uint8Array.prototype.toHex ??= function(){return Buffer.from(this).toString('hex')};
const E=await import('../src/engine.js');
const pdfjs=await import('pdfjs-dist/build/pdf.mjs');
pdfjs.GlobalWorkerOptions.workerSrc=new URL('../node_modules/pdfjs-dist/build/pdf.worker.mjs',import.meta.url).href;
const font=await fs.readFile(new URL('../dist/fonts/NotoSans-Regular.ttf',import.meta.url));
globalThis.fetch=async()=>new Response(font);
const file=(bytes,name='test.pdf')=>new File([bytes],name);
const source=await E.PDFDocument.create();
for(let i=0;i<3;i++)source.addPage([300+i*10,400]);
const fixture=file(await source.save());
assert.deepEqual(E.parsePages('3,1-2,1',3),[2,0,1]);
for(const range of ['0','4','2-1','1.5','1,'])assert.throws(()=>E.parsePages(range,3));
assert.equal((await E.PDFDocument.load(await E.mergePdfs([fixture,fixture]))).getPageCount(),6);
const selection=await E.PDFDocument.load(await E.selectPages(fixture,'3,1'));
assert.deepEqual(selection.getPages().map(p=>p.getWidth()),[320,300]);
assert.equal((await E.PDFDocument.load(await E.selectPages(fixture,'2',true))).getPageCount(),2);
await assert.rejects(()=>E.selectPages(fixture,'1-3',true),/Keep at least one/);
const generated=await E.textPdf({title:'Unicode test',text:'Café Ελληνικά — text survives.'});
assert.match((await E.pdfText(file(generated))).join(' '),/Café Ελληνικά/);
const longTitle=await E.PDFDocument.load(await E.textPdf({title:'Long title '.repeat(800),text:'Final body.'}));
assert.ok(longTitle.getPageCount()>1,'long titles must paginate');
const ExcelJS=(await import('exceljs')).default;
const wb=new ExcelJS.Workbook();const sheet=wb.addWorksheet('Values');
sheet.addRow([{formula:'1-1',result:0},{formula:'1=2',result:false},new Date('2026-10-01T00:00:00Z')]);
const sheetText=await E.sheetToText(file(await wb.xlsx.writeBuffer(),'values.xlsx'));
assert.match(sheetText,/0\s+\|\s+false\s+\|\s+2026-10-01/);
const xlsx=await E.textToXlsx(['One\nTwo']);const check=new ExcelJS.Workbook();await check.xlsx.load(xlsx);
assert.equal(check.worksheets[0].getCell('A2').value,'Two');
const docx=await E.textToDocx(['Hello document']);const zip=await E.JSZip.loadAsync(docx);
assert.match(await zip.file('word/document.xml').async('string'),/Hello document/);
assert.match(E.summarize(['First sentence. Second sentence.']),/First sentence/);
console.log('Engine regressions passed: page ranges, merge, extraction/removal, Unicode, title pagination, spreadsheet values, XLSX/DOCX export, summary.');
